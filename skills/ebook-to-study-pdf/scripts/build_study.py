"""Build a template-based study book from one explicit Markdown or TeX source of truth."""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from pdf_workflow import load_manifest, project_path, sha256

INDEX_MARKER = "% Generated by ebook-to-study-pdf; edit manifest, not this index.\n"


def run_tool(arguments: list[str], root: Path, log: Path, timeout: int) -> None:
    with log.open("w", encoding="utf-8") as stream:
        try:
            result = subprocess.run(
                arguments,
                cwd=root,
                stdout=stream,
                stderr=subprocess.STDOUT,
                timeout=timeout,
                check=False,
            )
        except subprocess.TimeoutExpired as error:
            raise RuntimeError(f"{arguments[0]} timed out; inspect {log}") from error
    if result.returncode:
        raise RuntimeError(f"{arguments[0]} exited {result.returncode}; inspect {log}")


def build(manifest: Path, timeout: int = 300) -> dict:
    root, data = load_manifest(manifest)
    mode = data.get("mode", "markdown")
    if mode not in {"markdown", "tex"}:
        raise ValueError("mode must be markdown or tex")
    if not 1 <= timeout <= 3600:
        raise ValueError("timeout must be in 1..3600 seconds per command")
    output = project_path(root, data.get("output", "总结.pdf"))
    if output.suffix.lower() != ".pdf" or output == (root / data["source"]).resolve():
        raise ValueError("Output must be a PDF distinct from the source")
    if output.relative_to(root).parts[0] in {"latex", "notes", "chapters", "source", "tmp"}:
        raise ValueError("Final output must not overwrite content/source/intermediate directories")
    main = root / "latex/main.tex"
    index = root / "latex/chapters.tex"
    if not main.is_file():
        raise ValueError("Copy assets/latex into the project and set BookTitle before building")
    if index.exists() and not index.read_text(encoding="utf-8").startswith(INDEX_MARKER):
        raise ValueError("Refusing to overwrite a non-generated latex/chapters.tex")
    filter_path = root / "latex/learning-blocks.lua"
    if mode == "markdown" and not filter_path.is_file():
        raise ValueError("Markdown build requires latex/learning-blocks.lua")
    jobs, targets, notes = [], set(), set()
    for ch in data["chapters"]:
        target = project_path(root, ch.get("tex"))
        relative = target.relative_to(root).as_posix()
        if (
            not relative.startswith("latex/chapters/")
            or target.suffix != ".tex"
            or re.search(r"[#$%&~^{}\\\"]", relative)
        ):
            raise ValueError("Chapter TeX must be a TeX-safe path under latex/chapters")
        if target in targets:
            raise ValueError("Chapter TeX targets must be unique")
        targets.add(target)
        if mode == "markdown":
            note = project_path(root, ch.get("note"))
            if not note.is_file() or note.suffix != ".md" or note in notes:
                raise ValueError("Each Markdown chapter needs its own existing .md source")
            notes.add(note)
        else:
            note = None
            if not target.is_file():
                raise ValueError(f"Missing TeX source: {relative}")
        jobs.append((ch["id"], note, target, relative))
    required = ["latexmk", "lualatex"] + (["pandoc"] if mode == "markdown" else [])
    tools = {name: shutil.which(name) for name in required}
    missing = [name for name, path in tools.items() if not path]
    if missing:
        raise RuntimeError("Missing toolchain: " + ", ".join(missing))
    scratch = root / "tmp/pdfs"
    scratch.mkdir(parents=True, exist_ok=True)
    builddir = Path(tempfile.mkdtemp(prefix="build-", dir=scratch))
    for identifier, note, target, relative in jobs:
        if mode == "markdown":
            generated = builddir / f"{identifier}.tex"
            run_tool(
                [
                    tools["pandoc"],
                    str(note),
                    "--from=markdown+raw_tex+fenced_divs",
                    "--to=latex",
                    "--top-level-division=chapter",
                    f"--lua-filter={filter_path}",
                    "--wrap=none",
                    "--syntax-highlighting=none",
                    f"--metadata=chapter-id:{identifier}",
                    f"--output={generated}",
                ],
                root,
                builddir / f"pandoc-{identifier}.log",
                timeout,
            )
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(generated, target)
    index.write_text(
        INDEX_MARKER + "".join(f'\\input{{"{relative}"}}\n' for _, _, _, relative in jobs),
        encoding="utf-8",
    )
    run_tool(
        [
            tools["latexmk"],
            "-lualatex",
            "-interaction=nonstopmode",
            "-halt-on-error",
            "-no-shell-escape",
            "-recorder",
            "-jobname=study",
            f"-outdir={builddir}",
            "latex/main.tex",
        ],
        root,
        builddir / "latexmk.log",
        timeout,
    )
    pdf = builddir / "study.pdf"
    if not pdf.is_file():
        raise RuntimeError(f"No newly built PDF; inspect {builddir}")
    final_log = (builddir / "study.log").read_text(encoding="utf-8", errors="replace")
    blockers = [
        line.strip()
        for line in final_log.splitlines()
        if re.search(
            r"Missing character:|Overfull \\[hv]box|undefined references|Reference .* undefined|Citation .* undefined|destination with the same identifier|duplicate ignored",
            line,
            re.I,
        )
    ]
    if blockers:
        raise RuntimeError(
            "Resolve PDF quality blockers before delivery: "
            + "; ".join(blockers[:12])
            + f"; logs: {builddir}"
        )
    import pymupdf

    with pymupdf.open(pdf) as doc:
        sizes = sorted({(round(p.rect.width, 1), round(p.rect.height, 1)) for p in doc})
        if not len(doc) or any(abs(w - 595.3) > 1 or abs(h - 841.9) > 1 for w, h in sizes):
            raise RuntimeError("Built PDF must contain A4 pages")
        pages = len(doc)
        # Font embedding is independently reported, not inferred from font names.
        fonts = {}
        for page in doc:
            for font in page.get_fonts(full=True):
                xref, _, _, base, _, _, *_ = font
                if xref not in fonts:
                    name, ext, kind, content = doc.extract_font(xref)
                    fonts[xref] = {"name": base, "embedded": bool(content)}
        unembedded = [font["name"] for font in fonts.values() if not font["embedded"]]
        if unembedded:
            raise RuntimeError("Unembedded fonts: " + ", ".join(unembedded))
    output.parent.mkdir(parents=True, exist_ok=True)
    staged = builddir / "delivery.pdf"
    shutil.copyfile(pdf, staged)
    # Same-filesystem replacement leaves an old final PDF intact on copy/lock failure.
    staged.replace(output)
    return {
        "output": str(output),
        "sha256": sha256(output),
        "pages": pages,
        "sizes_pt": sizes,
        "fonts": list(fonts.values()),
        "mode": mode,
        "logs": str(builddir),
        "status": "BUILT; content and visual acceptance still required",
    }


def main() -> int:
    import json

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("--timeout", type=int, default=300, help="Seconds per command")
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.manifest, args.timeout), ensure_ascii=False, indent=2))
        return 0
    except (OSError, ValueError, RuntimeError, ImportError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
